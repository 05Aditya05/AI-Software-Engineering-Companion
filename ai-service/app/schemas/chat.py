"""
Chat request, response, message, and error schemas.

Defines the payload contracts for the AI Service domain and API layers.
In Phase 4, these schemas will be extended with token streaming parameters
and LLM provider configuration.
"""

from enum import Enum
from typing import Any
from pydantic import BaseModel, Field


class MessageRole(str, Enum):
    """Roles for messages within a conversation history."""

    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"


class ChatMessage(BaseModel):
    """An individual message in a conversation session."""

    role: MessageRole = Field(
        ...,
        description="Role of the entity who created this message."
    )
    content: str = Field(
        ...,
        min_length=1,
        description="Text content of the message."
    )
    timestamp: str = Field(
        ...,
        description="ISO 8601 UTC timestamp of message creation."
    )
    metadata: dict[str, Any] | None = Field(
        default=None,
        description="Optional metadata attached to this message."
    )


class ScreenContextPayload(BaseModel):
    """
    Structured payload for user-permitted screen context capture (Phase 14).
    
    Guarantees:
      - Explicit user permission required (user_granted_permission must be True).
      - Ephemeral context: never persisted to long-term memory.
      - Includes window title and optional base64 image data.
    """
    image_base64: str | None = Field(default=None, description="Base64-encoded image data")
    mime_type: str = Field(default="image/jpeg", description="MIME type of screen capture")
    window_title: str | None = Field(default=None, description="Title of the captured window")
    display_name: str | None = Field(default=None, description="Display/monitor identifier")
    user_granted_permission: bool = Field(default=False, description="Whether user explicitly granted permission")
    captured_at: str | None = Field(default=None, description="ISO timestamp of capture")


class ChatRequest(BaseModel):
    """Payload sent to the AI service to initiate or continue a chat."""

    message: str = Field(
        ...,
        min_length=1,
        description="User message content. Must not be empty.",
        examples=["Hello companion!"]
    )
    conversation_id: str | None = Field(
        default=None,
        description="Optional unique identifier for the conversation session.",
        examples=["conv-123e4567-e89b-12d3-a456-426614174000"]
    )
    client_metadata: dict[str, Any] | None = Field(
        default=None,
        description="Optional client context or metadata."
    )
    screen_context: ScreenContextPayload | None = Field(
        default=None,
        description="Optional user-permitted screen context (Phase 14)."
    )


class ChatResponse(BaseModel):
    """Payload returned by the AI service back to caller."""

    message: str = Field(
        ...,
        description="Response message generated by the AI service."
    )
    source: str = Field(
        default="ai-service",
        description="Identifier of the replying service component."
    )
    conversation_id: str = Field(
        ...,
        description="Active conversation session ID."
    )
    timestamp: str = Field(
        ...,
        description="ISO 8601 UTC timestamp of response generation."
    )
    status: str = Field(
        default="success",
        description="Status string of the processing."
    )
    meta: dict[str, Any] | None = Field(
        default=None,
        description="Additional processing metadata."
    )


class ErrorDetail(BaseModel):
    """Structured error information."""

    code: str = Field(..., description="Machine-readable error code.")
    message: str = Field(..., description="Human-readable error description.")
    details: Any | None = Field(default=None, description="Optional extra error context.")


class ErrorResponse(BaseModel):
    """Standard error response envelope."""

    status: str = Field(default="error", description="Always 'error' for failure responses.")
    error: ErrorDetail = Field(..., description="Detailed error information.")
