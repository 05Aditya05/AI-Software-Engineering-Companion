"""
Chat request and response schemas.

Defines the payload contract for communication between the Backend
and the AI Service. In Phase 4, these schemas will be extended with
token streaming parameters and agent dispatch metadata.
"""

from typing import Any
from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    """Payload sent from the backend to the AI service."""

    message: str = Field(
        ...,
        min_length=1,
        description="User message content. Must not be empty.",
        examples=["Hello companion!"]
    )
    conversation_id: str | None = Field(
        default=None,
        description="Optional unique identifier for the conversation session.",
        examples=["conv-123e4567-e89b-12d3-a456-426614174000"]
    )
    client_metadata: dict[str, Any] | None = Field(
        default=None,
        description="Optional client context or metadata."
    )


class ChatResponse(BaseModel):
    """Payload returned by the AI service back to the backend."""

    message: str = Field(
        ...,
        description="Response message generated by the AI service."
    )
    source: str = Field(
        default="ai-service",
        description="Identifier of the replying service component."
    )
    conversation_id: str = Field(
        ...,
        description="Active conversation session ID."
    )
    timestamp: str = Field(
        ...,
        description="ISO 8601 UTC timestamp of response generation."
    )
    status: str = Field(
        default="success",
        description="Status code/string of the processing."
    )
    meta: dict[str, Any] | None = Field(
        default=None,
        description="Additional processing metadata (e.g. echo metadata, mock tags)."
    )
